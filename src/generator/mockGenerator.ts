import * as fs from 'fs';
import * as path from 'path';
import * as prettier from 'prettier';
import * as ts from 'typescript';

import {
  ClassDeclaration,
  InterfaceDeclaration,
  isClassDeclaration,
  isInterfaceDeclaration,
  isMethodDeclaration,
  isPropertySignature,
  SourceFile,
} from 'typescript';

import { hasMockableDecorator } from '../index';
import { createPath, defaultInputDir, defaultOutputDir, defaultServiceMocksFilePath } from '../utils';

export interface GenerateMocksOptions {
  inputDir?: string;
  outputDir?: string;
  outputFileName?: string;
}

const getMethodNames = (declaration: ClassDeclaration | InterfaceDeclaration): string[] =>
  declaration.members
    .filter(member => isMethodDeclaration(member) || isPropertySignature(member))
    .map(member => member.name?.getText())
    .filter((name): name is string => Boolean(name));

const getRelativeImportPath = (sourceFilePath: string, outputDir: string): string => {
  const absoluteSource = path.resolve(sourceFilePath);
  const absoluteOutputDir = path.resolve(outputDir);
  const withoutExtension = absoluteSource.replace(/\.ts$/, '');
  const relative = path.relative(absoluteOutputDir, withoutExtension).replace(/\\/g, '/');
  return relative.startsWith('.') ? relative : `./${relative}`;
};

const buildMockFactory = (
  declaration: ClassDeclaration | InterfaceDeclaration,
  importName: string,
  sourceFilePath: string,
  outputDir: string,
): string => {
  const declarationName = declaration.name?.getText();
  if (!declarationName) return '';

  const factoryName = `create${declarationName}Mock`;
  const members = getMethodNames(declaration);
  const importPath = getRelativeImportPath(sourceFilePath, outputDir);

  return [
    `import { ${declarationName} as ${importName} } from '${importPath}';`,
    '',
    `export const ${factoryName} = (): jest.Mocked<${importName}> => {`,
    `  const mock = {} as unknown as jest.Mocked<${importName}>;`,
    ...members.map(member => `  mock.${member} = jest.fn();`),
    '  return mock;',
    '};',
  ].join('\n');
};

const readTypeScriptFiles = (dir: string): string[] => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.flatMap(entry => {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return readTypeScriptFiles(entryPath);
    if (entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
      return [entryPath];
    }
    return [];
  });
};

export const generateMocks = async (options: GenerateMocksOptions = {}): Promise<void> => {
  const inputDir = options.inputDir ?? defaultInputDir;
  const outputDir = options.outputDir ?? defaultOutputDir;
  const outputFileName = options.outputFileName ?? 'mocks.ts';
  const outputPath = path.join(outputDir, outputFileName);

  const filePaths = readTypeScriptFiles(inputDir);
  if (filePaths.length === 0) {
    throw new Error(`No TypeScript input files found in '${inputDir}'.`);
  }

  const sourceFiles = filePaths.map(filePath =>
    ts.createSourceFile(filePath, fs.readFileSync(filePath, 'utf8'), ts.ScriptTarget.Latest, true),
  );

  const declarations = sourceFiles.flatMap(sourceFile =>
    sourceFile.statements.filter(
      statement =>
        (isClassDeclaration(statement) || isInterfaceDeclaration(statement)) &&
        hasMockableDecorator(statement),
    ),
  ) as (ClassDeclaration | InterfaceDeclaration)[];

  if (declarations.length === 0) {
    throw new Error(`No @Mockable classes or interfaces found in '${inputDir}'.`);
  }

  createPath(outputDir);

  const usedImportNames = new Set<string>();
  const sections = declarations.map((declaration, index) => {
    const declarationName = declaration.name?.getText() ?? `Declaration${index + 1}`;
    let importName = declarationName;
    let suffix = 1;
    while (usedImportNames.has(importName)) {
      importName = `${declarationName}_${++suffix}`;
    }
    usedImportNames.add(importName);

    const sourceFile = declaration.getSourceFile() as SourceFile;
    return buildMockFactory(declaration, importName, sourceFile.fileName, outputDir);
  });

  const generated = `// Generated by mockable. Do not edit.\n\n${sections.join('\n\n')}`;
  const formatted = await prettier.format(generated, { parser: 'typescript', singleQuote: true });
  fs.writeFileSync(outputPath, formatted);
};
